"""Bounded exact first-order ODEs derived from quadratic potentials."""
from __future__ import annotations

import random
from fractions import Fraction
from typing import Any

TOPIC = "quadratic_potential_exact_first_order_ODEs"
VERIFIER = "independent_quadratic_potential_exact_ode_check"


def _pair(value: Fraction) -> list[int]:
    return [value.numerator, value.denominator]


def _read_pair(value: Any, *, max_abs: int, max_denominator: int) -> Fraction:
    if (
        not isinstance(value, list)
        or len(value) != 2
        or any(not isinstance(part, int) or isinstance(part, bool) for part in value)
    ):
        raise ValueError("values must be integer numerator/denominator pairs")
    numerator, denominator = value
    if abs(numerator) > max_abs or not 1 <= denominator <= max_denominator:
        raise ValueError("value exceeds configured rational bounds")
    result = Fraction(numerator, denominator)
    if [result.numerator, result.denominator] != value:
        raise ValueError("rational pairs must be reduced and have positive denominators")
    return result


def _render(value: Fraction) -> str:
    return str(value.numerator) if value.denominator == 1 else f"{value.numerator}/{value.denominator}"


def _potential(a: Fraction, b: Fraction, c: Fraction, x: Fraction, y: Fraction) -> Fraction:
    return a * x * x + b * x * y + c * y * y


def _canonical(
    seed: int,
    difficulty: int,
    coefficients: tuple[Fraction, Fraction, Fraction],
    initial_point: tuple[Fraction, Fraction],
) -> dict:
    a, b, c = coefficients
    x0, y0 = initial_point
    m0 = 2 * a * x0 + b * y0
    n0 = b * x0 + 2 * c * y0
    constant = _potential(a, b, c, x0, y0)
    m_text = f"({_render(2*a)})x+({_render(b)})y"
    n_text = f"({_render(b)})x+({_render(2*c)})y"
    potential_text = (
        f"({_render(a)})x^2+({_render(b)})xy+({_render(c)})y^2"
    )
    return {
        "id": f"university-{TOPIC}-{seed}-{difficulty}",
        "seed": seed,
        "grade_band": "University",
        "topic": TOPIC,
        "subtopic": "exact equations generated by a quadratic potential in two variables",
        "difficulty": difficulty,
        "problem": (
            f"Solve ({m_text}) dx + ({n_text}) dy = 0 through the initial point "
            f"({_render(x0)},{_render(y0)})."
        ),
        "steps": [
            f"Let Phi(x,y)={potential_text}.",
            f"∂M/∂y={_render(b)} and ∂N/∂x={_render(b)}, so the equation is exact.",
            f"Evaluate Phi at the initial point: C={_render(constant)}.",
            f"The implicit solution is {potential_text}={_render(constant)}.",
        ],
        "answer": f"{potential_text}={_render(constant)}",
        "answer_type": "expression",
        "ingredients": {
            "topic": TOPIC,
            "potential_coefficients": [_pair(a), _pair(b), _pair(c)],
            "initial_point": [_pair(x0), _pair(y0)],
            "initial_partials": [_pair(m0), _pair(n0)],
            "potential_constant": _pair(constant),
        },
        "verifier": VERIFIER,
    }


def build_quadratic_potential_exact_ode_fields(rng: random.Random, difficulty: int):
    d = difficulty
    while True:
        coefficients = tuple(
            Fraction(rng.randint(-2 * d, 2 * d), rng.randint(1, d))
            for _ in range(3)
        )
        if any(coefficients):
            break
    initial_point = tuple(
        Fraction(rng.randint(-2 * d, 2 * d), rng.randint(1, d))
        for _ in range(2)
    )
    fields = _canonical(0, d, coefficients, initial_point)
    fields.pop("id")
    fields.pop("seed")
    return fields, lambda: verify_quadratic_potential_exact_ode({
        **fields,
        "id": f"university-{TOPIC}-0-{d}",
        "seed": 0,
    })


def verify_quadratic_potential_exact_ode(problem: dict) -> bool:
    try:
        if not isinstance(problem, dict) or problem.get("topic") != TOPIC:
            return False
        difficulty = problem.get("difficulty")
        seed = problem.get("seed")
        if not isinstance(difficulty, int) or isinstance(difficulty, bool) or difficulty not in (1, 2, 3, 4, 5):
            return False
        if not isinstance(seed, int) or isinstance(seed, bool):
            return False
        data = problem.get("ingredients")
        if not isinstance(data, dict) or data.get("topic") != TOPIC:
            return False
        d = difficulty
        raw_coefficients = data.get("potential_coefficients")
        raw_point = data.get("initial_point")
        if not isinstance(raw_coefficients, list) or len(raw_coefficients) != 3:
            return False
        if not isinstance(raw_point, list) or len(raw_point) != 2:
            return False
        coefficients = tuple(
            _read_pair(value, max_abs=2 * d, max_denominator=d)
            for value in raw_coefficients
        )
        point = tuple(
            _read_pair(value, max_abs=2 * d, max_denominator=d)
            for value in raw_point
        )
        if not any(coefficients):
            return False
        return problem == _canonical(seed, difficulty, coefficients, point)
    except (KeyError, TypeError, ValueError, ZeroDivisionError, OverflowError):
        return False
